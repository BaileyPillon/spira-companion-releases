"""Generate the Mix recipe IDs from an extracted FFX battle/kernel/prepare.bin."""

import argparse
import json
import struct
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("prepare", type=Path, help="Mix table from your own game data")
    parser.add_argument("output", type=Path, nargs="?", default=Path("app/assets/ffx-mix-data.js"))
    args = parser.parse_args()

    data = args.prepare.read_bytes()
    item_count = 112
    header_size = 20
    first_result = 0x308B
    if len(data) != header_size + item_count * item_count * 2:
        parser.error("Unexpected FFX Mix table size")
    rows = [
        [result - first_result for result in struct.unpack_from(
            f"<{high + 1}H", data, header_size + 2 * item_count * high
        )]
        for high in range(item_count)
    ]
    if {result for row in rows for result in row} != set(range(64)):
        parser.error("Unexpected result IDs in FFX Mix table")

    # Upper item ID selects the row and lower ID selects its column.
    # Store only the valid half of the table. The result names are in ffx-data.js.
    args.output.write_text(
        "// Generated by generate-ffx-mix.py\nconst ffxMixRows = [\n"
        + ",\n".join("  " + json.dumps(row, separators=(",", ":")) for row in rows)
        + "\n];\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
