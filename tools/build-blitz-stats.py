"""Extract numeric reference facts; no upstream application code is bundled.

Input: data/players.json from theadamantium/BlitzballAppv2 at
af16b58179739dd46d610e8aefd4fc1ab7bd7fc1. Pass its local path as argv[1].
"""
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
source = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8-sig"))["players"]
aliases = {name: name + " Ronso" for name in ("Basik", "Argai", "Gazna", "Nuvy", "Irga", "Zamzi", "Zev")}
aliases.update({name: name + " Guado" for name in ("Giera", "Zazi", "Auda", "Pah", "Noy", "Yuma")})
aliases["Navara"] = "Nav Guado"
keys = ["HP", "speed", "endurance", "attack", "pass", "block", "shot", "catch"]
data = {}
for player in source:
    name = aliases.get(player["name"], player["name"])
    rows = [[sample["level"], *[sample[key] for key in keys]] for sample in player["stats"]]
    assert rows and rows[-1][0] == 99
    assert all(a[0] < b[0] for a, b in zip(rows, rows[1:]))
    assert all(isinstance(value, int) and 0 <= value <= (9999 if i == 1 else 99)
               for row in rows for i, value in enumerate(row))
    assert name not in data
    location = player["location"].replace(" -- ", " · ")
    if location.lower() == "n/a":
        location = "Traveling party"
    data[name] = {"location": location, "samples": rows}
assert len(data) == 60
output = '// Generated by tools/build-blitz-stats.py. Factual reference samples, not live stats.\n'
output += '// Source: https://github.com/theadamantium/BlitzballAppv2/blob/af16b58179739dd46d610e8aefd4fc1ab7bd7fc1/data/players.json\n'
output += '"use strict";\nconst blitzStatReference = ' + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ';\n'
(root / "app/assets/ffx-blitz-stats-data.js").write_text(output, encoding="utf-8")
print(f"Extracted {len(data)} players and {sum(len(p['samples']) for p in data.values())} reference samples.")
